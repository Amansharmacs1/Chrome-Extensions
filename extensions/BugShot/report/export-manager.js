/**
 * BugShot - Export & Sharing Manager
 * Produces structured JSON schemas, GitHub/Jira-flavored Markdown templates,
 * formatted plain text summaries, and print-ready stylesheets for native PDF saving.
 */

/**
 * Generates a clean, standardized JSON export string
 * @param {import('../src/types').BugReport} report
 * @param {boolean} [includeScreenshot=false]
 * @returns {string}
 */
export function generateJsonExport(report, includeScreenshot = false) {
  if (!report) return '{}';

  const exportObj = {
    $schema: 'https://bugshot.dev/schemas/bug-report-v1.json',
    generator: 'BugShot Chrome Extension v1.0.0',
    exportedAt: new Date().toISOString(),
    report: {
      id: report.id,
      title: report.title,
      category: report.category,
      severity: report.severity,
      priority: report.priority,
      status: report.status || 'open',
      createdAt: new Date(report.createdAt).toISOString(),
      updatedAt: new Date(report.updatedAt).toISOString(),
      description: report.description,
      stepsToReproduce: report.stepsToReproduce,
      expectedResult: report.expectedResult,
      actualResult: report.actualResult,
      tags: report.tags || []
    },
    environment: report.metadata,
    diagnostics: {
      consoleErrors: (report.consoleLogs || []).filter(l => l.included !== false),
      networkFailures: (report.networkInsights || []).filter(n => n.included !== false)
    }
  };

  if (includeScreenshot && report.screenshotAnnotated) {
    exportObj.screenshot = report.screenshotAnnotated;
  }

  return JSON.stringify(exportObj, null, 2);
}

/**
 * Generates a GitHub / Jira / Linear ready Markdown document
 * @param {import('../src/types').BugReport} report
 * @returns {string}
 */
export function generateMarkdownExport(report) {
  if (!report) return '';

  const meta = report.metadata || {};
  const activeConsole = (report.consoleLogs || []).filter(l => l.included !== false);
  const activeNet = (report.networkInsights || []).filter(n => n.included !== false);

  const stepsFormatted = Array.isArray(report.stepsToReproduce) && report.stepsToReproduce.length > 0
    ? report.stepsToReproduce.map((s, idx) => `${idx + 1}. ${s}`).join('\n')
    : '_No explicit reproduction steps provided._';

  const parts = [];

  parts.push(`# 🐛 [${(report.severity || 'MEDIUM').toUpperCase()}] ${report.title || 'Untitled Bug Report'}`);
  parts.push('');
  parts.push(`> **Category:** \`${report.category || 'other'}\` | **Priority:** \`${report.priority || 'P2'}\` | **Report ID:** \`${report.id}\` | **Date:** ${new Date(report.createdAt).toUTCString()}`);
  parts.push('');
  parts.push('## 📝 Description');
  parts.push(report.description || '_No description provided._');
  parts.push('');
  parts.push('## 🔁 Steps to Reproduce');
  parts.push(stepsFormatted);
  parts.push('');
  parts.push('## 🎯 Expected vs Actual Behavior');
  parts.push('| Result | Details |');
  parts.push('| :--- | :--- |');
  parts.push(`| **Expected** | ${escapeMarkdown(report.expectedResult || 'Not specified')} |`);
  parts.push(`| **Actual** | ${escapeMarkdown(report.actualResult || 'Not specified')} |`);
  parts.push('');
  parts.push('## 💻 Technical Environment');
  parts.push('| Property | Value |');
  parts.push('| :--- | :--- |');
  parts.push(`| **Target URL** | \`${meta.url || 'N/A'}\` |`);
  parts.push(`| **Page Title** | ${escapeMarkdown(meta.title || 'N/A')} |`);
  parts.push(`| **Browser** | ${meta.browserName || 'Chrome'} ${meta.browserVersion || ''} |`);
  parts.push(`| **Operating System** | ${meta.os || 'N/A'} (${meta.platform || ''}) |`);
  parts.push(`| **Viewport Dimensions** | ${meta.viewportWidth || 0} × ${meta.viewportHeight || 0} px (DPR: ${meta.devicePixelRatio || 1}) |`);
  parts.push(`| **Screen Resolution** | ${meta.screenWidth || 0} × ${meta.screenHeight || 0} px |`);
  parts.push(`| **Language** | ${meta.language || 'en'} |`);
  parts.push('');

  if (activeConsole.length > 0) {
    parts.push('## ⚠️ Captured Console Errors');
    parts.push('```javascript');
    for (const log of activeConsole) {
      parts.push(`// [${new Date(log.timestamp).toLocaleTimeString()}] ${log.level.toUpperCase()}`);
      parts.push(log.message);
      if (log.stack) parts.push(log.stack);
      parts.push('');
    }
    parts.push('```');
    parts.push('');
  }

  if (activeNet.length > 0) {
    parts.push('## 🌐 Network Failures');
    parts.push('| Resource URL | Status | Duration | Type |');
    parts.push('| :--- | :--- | :--- | :--- |');
    for (const net of activeNet) {
      parts.push(`| \`${net.url}\` | **${net.status || 'ERR'}** (${net.statusText || 'Failed'}) | ${net.duration || 0}ms | ${net.resourceType || 'fetch'} |`);
    }
    parts.push('');
  }

  parts.push('---');
  parts.push('_Generated by [BugShot](https://bugshot.dev) Chrome Extension._');

  return parts.join('\n');
}

/**
 * Produces a concise plain text snippet for Slack / Discord / chat sharing
 * @param {import('../src/types').BugReport} report
 * @returns {string}
 */
export function generateQuickSummary(report) {
  if (!report) return '';
  return `[${(report.severity || 'MEDIUM').toUpperCase()}] ${report.title}
Category: ${report.category} | Priority: ${report.priority}
URL: ${report.metadata?.url || 'N/A'}
Expected: ${report.expectedResult || 'N/A'}
Actual: ${report.actualResult || 'N/A'}
Reported via BugShot`;
}

function escapeMarkdown(text = '') {
  return String(text).replace(/\|/g, '\\|').replace(/\n/g, '<br/>');
}
